import assert from 'node:assert/strict';
import {createElement as h} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {createHpItemGame,saveHpItemGame,HP_ITEM_STORAGE_KEY,HP_ITEM_SHOP_STORAGE_KEY} from '../lib/hp-item-mode.ts';
import {readSaveSlots,type SaveSlot} from '../lib/save-slots.ts';
import {HpItemLobby,HpItemResult,HpItemShop} from '../app/components/HpItemMatch.tsx';
import {ResumePicker} from '../app/components/SinglePlayer.tsx';
import {view} from '../lib/game.ts';
const memory=new Map<string,string>(),storage={getItem:(key:string)=>memory.get(key)||null,setItem:(key:string,value:string)=>{memory.set(key,value);}};
const retired=createHpItemGame('이전 기본','',Date.now(),1),active=createHpItemGame('현재 전투','',Date.now(),2);
saveHpItemGame(storage,retired);saveHpItemGame(storage,active);
const original=[...memory.entries()],found=readSaveSlots(storage);
assert.deepEqual(found.slots.map(slot=>slot.mode),['hp-item-2']);assert.equal(found.errors.length,0);
assert.deepEqual(found.slots[0].game,JSON.parse(JSON.stringify(active)));assert.deepEqual([...memory.entries()],original);
assert.equal(found.slots[0].title,'아이템전 · 포인트 상점·전투·스킬');
const legacySlot:SaveSlot={mode:'hp-item',title:'아이템전1',detail:'이전 기본',game:retired,session:{code:retired.code,token:retired.players[0].token,local:true}},noop=()=>{};
const picker=renderToStaticMarkup(h(ResumePicker,{slots:[legacySlot,...found.slots],errors:[],choose:noop,close:noop}));
assert.ok(!picker.includes('아이템전1'));assert.ok(picker.includes('포인트 상점·전투·스킬'));
const archive={version:1 as const,active,records:[]};
const lobby=renderToStaticMarkup(h(HpItemLobby,{archive,start:noop,resume:noop,close:noop,error:'',character:'toto',chooseCharacter:noop}));
assert.ok(lobby.includes('<h2>아이템전</h2>'));assert.ok(lobby.includes('아이템전 이어하기')&&lobby.includes('새 아이템전 시작'));
assert.ok(lobby.includes('30명')&&lobby.includes('hp-character-picker')&&lobby.includes('20P로 상점에서 선택 구매'));
for(const retiredLabel of ['아이템전1','아이템전2','segmented','판 종료 시 아이템 효과'])assert.ok(!lobby.includes(retiredLabel));
const gameView=view(active,active.players[0].token),shop=renderToStaticMarkup(h(HpItemShop,{game:gameView,busy:false,error:'',buy:noop,exit:noop}));
assert.ok(shop.includes('아이템전 · 1판 준비')&&!shop.includes('아이템전2'));
const result=renderToStaticMarkup(h(HpItemResult,{game:gameView,busy:false,next:noop,restart:noop,exit:noop}));assert.ok(!result.includes('아이템전2'));
const kept=memory.get(HP_ITEM_SHOP_STORAGE_KEY);memory.set(HP_ITEM_STORAGE_KEY,'{broken');
assert.equal(readSaveSlots(storage).errors.length,0,'retired mode corruption is not reported as an active-game error');
assert.equal(memory.get(HP_ITEM_STORAGE_KEY),'{broken');assert.equal(memory.get(HP_ITEM_SHOP_STORAGE_KEY),kept);
console.log('PASS: mode-1 entry/resume removed without deleting saves; current wallet/skills/roster retained and all active UI uses one item-mode name.');
