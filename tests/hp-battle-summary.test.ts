import assert from 'node:assert/strict';
import {hpBattleSummary} from '../lib/hp-battle-summary.ts';
import type {HpBattleEvent} from '../lib/hp-item-battle.ts';
const players=[{name:'나',count:6},{name:'로웬',count:4},{name:'루미',count:5}];
const event:HpBattleEvent={id:'example',round:1,actor:0,label:'싱글',damage:1,hpBefore:[70,81,87],hpAfter:[70,80,86],at:0};
const summary=hpBattleSummary(event,players);
assert.deepEqual(summary.rows.map(row=>row.seat),[2,1,0],'all characters appear by current HP, including a winner with less HP');
assert.deepEqual(summary.rows.map(row=>row.rank),[1,2,3]);
assert.deepEqual(summary.rows.map(row=>row.damage),[1,1,0]);
assert.equal(summary.rows[2].note,'승리 · 피해 없음');
assert.equal(summary.rows[0].note,'싸움 피해 −1');
assert.equal(summary.totalDamage,2);assert.equal(summary.text,'나 싱글 승리 · 총 HP 피해 2');
const guarded=hpBattleSummary({...event,hpAfter:[70,81,86]},players);
assert.equal(guarded.rows.find(row=>row.seat===1)!.note,'방어 · 피해 없음');assert.equal(guarded.totalDamage,1);
const tied=hpBattleSummary({...event,hpAfter:[80,80,80]},players);
assert.deepEqual(tied.rows.map(row=>row.seat),[1,2,0],'remaining-hand size breaks equal-HP standings');
const exact=hpBattleSummary({...event,hpAfter:[80,80,80]},players.map(player=>({...player,count:5})));
assert.deepEqual(exact.rows.map(row=>row.seat),[0,1,2],'exact ties have stable display order and sequential places');
assert.deepEqual(event.hpAfter,[70,80,86],'display sorting does not mutate game HP');
console.log('PASS: all-character standings, fight-winner distinction, stable ties and persistent damage summary');
